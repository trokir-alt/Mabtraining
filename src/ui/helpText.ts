/** the button the help was opened from, and the right edge of the tool
    panel it sits in (0 outside one), all in viewport px */
export type Anchor = { left: number; top: number; right: number; bottom: number; panel: number }

type HelpState = {
  open: HelpKey | null
  /** the title as the button that opened it reads, e.g. «Номерной шар» on pool */
  title: string | null
  anchor: Anchor | null
  show: (key: HelpKey, anchor?: Anchor | null, title?: string) => void
  close: () => void
}

export const useHelp = create<HelpState>((set) => ({
  open: null,
  title: null,
  anchor: null,
  show: (key, anchor = null, title) => set({ open: key, anchor, title: title ?? null }),
  close: () => set({ open: null, anchor: null, title: null }),
}))
